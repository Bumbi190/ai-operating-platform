import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const root=new URL('../src/Root.tsx',import.meta.url)
const old=new URL('../src/compositions/ContentGrowthReel.tsx',import.meta.url)
const updated=new URL('../src/compositions/ThePromptEditorialLab.tsx',import.meta.url)
const rootCode=readFileSync(root,'utf8')
const oldCode=readFileSync(old,'utf8')
const lab=readFileSync(updated,'utf8')
const segment=(start,end)=>{
  const s=rootCode.indexOf('id="'+start+'"')
  const e=rootCode.indexOf(end,s)
  assert(s>=0&&e>s)
  return rootCode.slice(s,e)
}
const thePrompt=segment('ThePromptContentLab','/>')
const family=segment('FamiljeStundenContentLab','/>')
const production=segment('SimpleNewsReel','/>')

assert(thePrompt.includes('component={ThePromptEditorialLab}'),'new design lab component is wired')
assert(thePrompt.includes('durationInFrames={360}'),'creative preview 12s only')
assert(thePrompt.includes("sourceName:'EDITORIAL CONCEPT'"),'explicit concept content')
assert(family.includes('component={ContentGrowthReel}'),'family creative preview remains unchanged')
assert(production.includes('component={SimpleNewsReel}'),'existing twice-daily news composition untouched')
assert(oldCode.includes("'the-prompt': {"),'legacy reference retained')
assert(!lab.includes('KREATIVT UTKAST'),'the new lab must not default to Swedish')
assert(lab.includes('CONCEPT PREVIEW / NOT FOR POSTING'),'preview never claims publication approval')
assert(lab.includes('THE STORY IN 12 SECONDS'),'English first-frame hook')
assert(lab.includes('THE TAKEAWAY'),'separate explanation/payoff beat')
assert(lab.includes('FOLLOW'),'clear English CTA')
assert(lab.includes('sourceName'),'source/credit input')
assert(lab.includes('imageUrls'),'actual approved visuals are accepted as input')
for(const bad of ['fetch(', 'navigator.', 'localStorage.', 'sendTo', 'publishReel', 'lambdaRender'])
  assert(!lab.includes(bad),'creative preview may not perform side effects: '+bad)
console.log('PASS: The Prompt English editorial lab, source/visual slots, no outbound writes, family unchanged, scheduled composition unchanged.')
