import {test} from 'node:test'
import assert from 'node:assert/strict'
import {buildPilotVoiceReceipt} from '../../web/lib/media/pilot-voice-receipt'
const words=Array.from({length:17},(_,i)=>({word:'Victoria',startMs:i*500,endMs:i*500+470}))
const audio=Uint8Array.from(Array.from({length:600},(_,i)=>i%256))
test('canonical voice+model are recorded for real generated bytes',()=>{
  const receipt=buildPilotVoiceReceipt('A real AI news script',audio,words,10000)
  assert.equal(receipt.voiceId,'qSeXEcewz7tA0Q0qk9fH')
  assert.equal(receipt.modelId,'eleven_turbo_v2_5')
  assert.equal(receipt.durationMs,10000)
  assert.equal(receipt.wordCount,17)
  assert.equal(receipt.audioByteSize,600)
  assert.match(receipt.audioSha256,/^[a-f0-9]{64}$/)
  assert.match(receipt.timingsSha256,/^[a-f0-9]{64}$/)
  assert(!JSON.stringify(receipt).includes('A real AI news script'))
})
test('changing audio, words or narration changes immutable hash evidence',()=>{
  const normal=buildPilotVoiceReceipt('A real AI news script',audio,words,10000)
  const changed=Uint8Array.from(audio);changed[0]^=1
  assert.notEqual(buildPilotVoiceReceipt('A real AI news script',changed,words,10000).audioSha256,normal.audioSha256)
  assert.notEqual(buildPilotVoiceReceipt('Different script',audio,words,10000).transcriptSha256,normal.transcriptSha256)
  assert.notEqual(buildPilotVoiceReceipt('A real AI news script',audio,[...words.slice(0,-1),{...words.at(-1)!,endMs:9110}],10000).timingsSha256,normal.timingsSha256)
})
test('rejects malformed timings or implausible payloads rather than fabricating receipts',()=>{
  assert.throws(()=>buildPilotVoiceReceipt('script',new Uint8Array([1]),words,10000))
  assert.throws(()=>buildPilotVoiceReceipt('script',audio,[],10000))
  assert.throws(()=>buildPilotVoiceReceipt('script',audio,words,2000))
  assert.throws(()=>buildPilotVoiceReceipt('script',audio,[...words,{word:'wrong',startMs:300,endMs:310}],10000))
})
