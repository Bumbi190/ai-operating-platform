import {test} from 'node:test'
import assert from 'node:assert/strict'
import {createProviderPreview,PREVIEW_PROJECT_ID} from '../../web/lib/media/provider-preview'
const NOW=Date.parse('2026-10-18T06:00:00Z')
function setup(overrides:Record<string,unknown>={}){
 let saved:any=null,claims=0,images=0,voices=0,sourceReads=0,stopped=false
 const deps:any={
  env:{VERCEL_ENV:'preview',H1_SPEND_GATE:'1',ANTHROPIC_API_KEY:'test',IDEOGRAM_API_KEY:'test',ELEVENLABS_API_KEY:'test'},
  access:{ok:true,userId:'owner',allowedProjectIds:[PREVIEW_PROJECT_ID]},now:()=>NOW,
  read:async()=>saved,claim:async(state:any)=>{claims++;if(saved)return false;saved=structuredClone(state);return true},
  save:async(state:any)=>{saved=structuredClone(state)},
  verifySource:async()=>{sourceReads++},estimate:async()=>8.7,
  assertExecution:async()=>{if(stopped)throw Error('paused')},
  images:async()=>{images++;return['u0','u1','u2']},
  admitImage:async(_u:string,i:number)=>'image-'+i,
  voice:async()=>{voices++;return{audioBuffer:Buffer.alloc(300,1),words:Array.from({length:12},(_,i)=>({word:'word',startMs:i*1000,endMs:i*1000+800})),durationMs:13000}},
  admitVoice:async()=> 'audio-id',
  deliver:async(state:any)=>({imageIds:state.imageIds,audioId:state.audioId}),
  ...overrides,
 }
 return{service:createProviderPreview(deps),state:()=>saved,counters:()=>({claims,images,voices,sourceReads}),pause:()=>{stopped=true}}
}
test('quote is read-only; one completed attempt is reused without a second provider batch',async()=>{
 const x=setup(),q=await x.service.inspect()
 assert.equal(q.status,'ready_to_generate');assert.equal(q.maximumSek,12)
 assert.deepEqual(x.counters(),{claims:0,images:0,voices:0,sourceReads:0})
 const a=await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})
 assert.equal(a.status,'ready');assert.equal(x.state().imageIds.length,3)
 assert.equal(x.state().voiceReceipt.voiceId,'qSeXEcewz7tA0Q0qk9fH')
 const again=await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})
 assert.equal(again.status,'ready');assert.equal(x.counters().images,1);assert.equal(x.counters().voices,1)
})
test('two concurrent requests have one durable winner',async()=>{
 const x=setup(),q=await x.service.inspect()
 await Promise.all([x.service.generate({quoteHash:q.quoteHash,maximumSek:12}),x.service.generate({quoteHash:q.quoteHash,maximumSek:12})])
 assert.equal(x.counters().images,1);assert.equal(x.counters().voices,1)
})
test('ambiguous image failure is retained and cannot be regenerated by another POST',async()=>{
 let calls=0
 const x=setup({images:async()=>{calls++;throw Error('timeout may already be billed')}}),q=await x.service.inspect()
 assert.equal((await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})).status,'review_required')
 assert.equal((await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})).status,'review_required')
 assert.equal(calls,1);assert.equal(x.counters().voices,0)
})
test('every authorization/configuration/quote/source/stop refusal precedes the durable claim',async()=>{
 const bad=[
  {env:{VERCEL_ENV:'production'}},
  {access:{ok:true,userId:'foreign',allowedProjectIds:[]}},
  {env:{VERCEL_ENV:'preview',H1_SPEND_GATE:'0'}},
  {env:{VERCEL_ENV:'preview',H1_SPEND_GATE:'1',ANTHROPIC_API_KEY:'t',IDEOGRAM_API_KEY:'t'}},
  {now:()=>Date.parse('2026-10-19T06:00:00Z')},
  {estimate:async()=>12.01},
  {estimate:async()=>NaN},
  {verifySource:async()=>{throw Error('source changed')}},
  {assertExecution:async()=>{throw Error('paused')}},
 ]
 for(const override of bad){
  const x=setup(override)
  let q:any
  try{q=await x.service.inspect();await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})}catch{}
  assert.equal(x.counters().claims,0,JSON.stringify(Object.keys(override)))
  assert.equal(x.counters().images,0)
 }
 const x=setup(),q=await x.service.inspect()
 await assert.rejects(x.service.generate({quoteHash:q.quoteHash,maximumSek:13}))
 await assert.rejects(x.service.generate({quoteHash:'tampered',maximumSek:12}))
 assert.equal(x.counters().claims,0)
})
test('persistence refusal never reaches a provider',async()=>{
 const x=setup({claim:async()=>{throw Error('database unavailable')}}),q=await x.service.inspect()
 await assert.rejects(x.service.generate({quoteHash:q.quoteHash,maximumSek:12}))
 assert.equal(x.counters().images,0);assert.equal(x.counters().voices,0)
})
test('every admitted image is checkpointed before voice and a save failure cannot replay',async()=>{
 let saved:any=null
 const x=setup({read:async()=>saved,claim:async(s:any)=>{if(saved)return false;saved=s;return true},
 save:async(s:any)=>{if(s.imageIds.length===2)throw Error('save unavailable');saved=structuredClone(s)}})
 const q=await x.service.inspect()
 assert.equal((await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})).status,'review_required')
 await x.service.generate({quoteHash:q.quoteHash,maximumSek:12})
 assert.equal(x.counters().images,1);assert.equal(x.counters().voices,0)
})

test('source expiry during the network cross-check refuses before the claim',async()=>{
 let now=NOW
 const x=setup({now:()=>now,verifySource:async()=>{now=Date.parse('2026-10-20T06:00:00Z')}})
 const q=await x.service.inspect()
 await assert.rejects(x.service.generate({quoteHash:q.quoteHash,maximumSek:12}))
 assert.equal(x.counters().claims,0);assert.equal(x.counters().images,0)
})
