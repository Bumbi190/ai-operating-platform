test('an older preview keeps its own brief and feedback, with the newer plan clearly identified',async({page,request})=>{
 await page.goto('/?multiple=1')
 await expect(page.getByTitle('Webbpreview version 1')).toBeVisible({timeout:20000})
 await expect(page.getByText('Du visar ett äldre bygge. Planen och kopplingsguiderna nedan gäller samtalets senaste plan.',{exact:true})).toBeVisible()
 const brief=page.getByText('Byggets sparade brief',{exact:true})
 await brief.click()
 const savedBrief=brief.locator('..')
 await expect(savedBrief.getByText(/Första caféets hemsida/)).toBeVisible()
 await expect(savedBrief.getByText(/Andra caféets hemsida/)).toHaveCount(0)
 const plan=page.getByRole('region',{name:'Arkitekturplan'})
 await plan.locator('summary').click()
 await expect(plan.getByRole('button',{name:'Planen används av ett annat bygge',exact:true})).toBeDisabled()
 await expect(plan.getByRole('button',{name:'Planen används av bygget',exact:true})).toHaveCount(0)
 const query=new URL(page.url()).searchParams,oldId=query.get('viewSession')!
 const latest=await workspace(request,page)
 expect(latest.session.sessionId).not.toBe(oldId)
 await send(page,'Gör rubriken större i det äldre bygget')
 await expect(page.getByText('Mottagen',{exact:true})).toBeVisible()
 await request.get('/__fixture/step/'+oldId+'/commit')
 await expect(page.getByTitle('Webbpreview version 2')).toBeVisible()
 const after=await workspace(request,page)
 expect(after.session.sessionId).toBe(latest.session.sessionId)
 const old=await (await request.get('/__fixture/conversation/'+query.get('conversation')+'?viewSession='+oldId)).json()
 expect(old.session.feedback.at(-1).text).toBe('Gör rubriken större i det äldre bygget')
 expect(after.session.feedback).toHaveLength(0)
 await page.reload()
 await expect(page.getByTitle('Webbpreview version 2')).toBeVisible()
 await expect(page.getByText('Du visar ett äldre bygge. Planen och kopplingsguiderna nedan gäller samtalets senaste plan.',{exact:true})).toBeVisible()
})
