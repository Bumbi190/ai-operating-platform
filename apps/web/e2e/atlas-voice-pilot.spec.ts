for (const action of ['edit', 'stop', 'signout', 'correct'] as const) {
  test(action + ' prevents automatic dispatch of a waiting voice turn', async ({ page }) => {
    await page.goto('/atlas/rosttest')
    await page.getByRole('button', { name: 'Starta mikrofonen' }).click()
    await expect(page.getByRole('status').filter({ hasText: /^Atlas lyssnar$/ })).toBeVisible()
    await page.getByRole('button', { name: 'Säg första frågan' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Atlas pratar' })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: /^Atlas lyssnar$/ })).toBeVisible()
    await page.getByRole('button', { name: 'Säg första avbrottet' }).click()
    await expect(page.getByLabel('Det du vill säga')).toHaveValue('Lägg till en blå knapp.')
    if (action === 'correct') await page.getByRole('button', { name: 'Avbryt och rätta', exact: true }).click()
    if (action === 'edit') await page.getByLabel('Det du vill säga').fill('Granska först.')
    if (action === 'stop') await page.getByRole('button', { name: 'Stoppa allt ljud' }).click()
    if (action === 'signout') await page.getByRole('button', { name: 'Simulera utloggning' }).click()
    await page.getByRole('button', { name: 'Håll chattsvar: på' }).click()
    await page.getByRole('button', { name: 'Släpp chattsvar' }).click()
    await expect(page.getByRole('button', { name: 'Skicka', exact: true })).toBeEnabled()
    await expect(page.getByRole('status').filter({ hasText: 'Chattbegäranden: 1' })).toBeVisible()
    await expect(page.getByLabel('Det du vill säga')).toHaveValue(action === 'edit' ? 'Granska först.' : 'Lägg till en blå knapp.')
  })
}

test('three consecutive spoken questions each produce a reply and reopen listening', async ({ page }) => {
  await page.goto('/atlas/rosttest')
  await page.getByRole('button', { name: 'Håll chattsvar: på' }).click()
  await page.getByRole('button', { name: 'Starta mikrofonen' }).click()
  for (let turn = 1; turn <= 3; turn++) {
    await expect(page.getByRole('status').filter({ hasText: /^Atlas lyssnar$/ })).toBeVisible()
    await page.getByRole('button', { name: 'Säg första frågan' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Chattbegäranden: ' + turn })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Atlas pratar' })).toBeVisible()
  }
  await expect(page.getByRole('status').filter({ hasText: /^Atlas lyssnar$/ })).toBeVisible()
})

