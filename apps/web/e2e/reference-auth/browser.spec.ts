import {test,expect,type Page,type BrowserContext} from '@playwright/test'
const fixture=JSON.parse(process.env.ATLAS_REFERENCE_BROWSER_FIXTURE!)
const query=new URLSearchParams({projectId:fixture.projectId,conversationId:fixture.conversationId})
const comment='Behåll ordningen och färgerna från mina privata referenser.'
async function guard(context:BrowserContext){
 const external:string[]=[]
 context.on('page',page=>page.on('console',message=>{if(message.type()==='error')console.error('browser: '+message.text())}))
 await context.route('**/*',route=>{
  const u=new URL(route.request().url())
  if(![fixture.appUrl,fixture.storageUrl].includes(u.origin)){external.push(u.origin);return route.abort('blockedbyclient')}
  return route.continue()
 })
 return external
}
async function login(page:Page,email=fixture.ownerEmail){
 console.log('browser phase: password login')
 await page.goto('/login')
 await page.getByLabel('E-postadress',{exact:true}).fill(email)
 await page.getByLabel('Lösenord',{exact:true}).fill(fixture.password)
 await page.locator('button[type=submit]').click()
 await expect(page).toHaveURL(/[/]dashboard$/)
 await expect(page.getByTestId('verified-user')).toHaveText(email)
}
async function api(page:Page,path:string,body?:unknown){
 return page.evaluate(async({path,body})=>{
  const r=await fetch(path,{method:body===undefined?'GET':'POST',headers:{'content-type':'application/json'},...(body===undefined?{}:{body:JSON.stringify(body)})})
  return {status:r.status,body:await r.json()}
 },{path,body})
}
