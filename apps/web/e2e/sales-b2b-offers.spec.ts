import {test,expect} from '@playwright/test'
const projectId='10000000-0000-4000-8000-000000000002'
test('WebBuilder saves confirmed service offers without pilot months or inherited product facts',async({page,context})=>{
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 const model:any={projectId,state:'ok',workerState:'not_connected',contacts:[],offers:[],jobs:[],drafts:[],evidence:[],workers:[],emailTemplates:[],workspaceUrl:'/projects/webbuilder/sales',sendingEnabled:false,timing:{projectId,evaluatedAt:'2026-10-31T10:00:00Z',historyRevisions:[],rules:null,customerSendingEnabled:false,contacts:[],workspaceUrl:'/sales#contact-timing'}}
 const writes:any[]=[]
 await page.route('**/api/sales?*',route=>route.fulfill({json:new URL(route.request().url()).searchParams.has('connection')?{connections:[],sendingEnabled:false}:model}))
 await page.route('**/api/sales/mailbox?*',route=>route.fulfill({json:null}))
 await page.route('**/api/sales',async route=>{
  const value=route.request().postDataJSON();writes.push(value)
  expect(value.projectId).toBe(projectId)
  if(value.operation==='save_offer')model.offers.unshift({...value,createdAt:'2026-10-31T10:00:00Z'})
  else if(value.operation==='save_contact'){
   model.contacts.push({...value,version:1})
   model.timing.contacts.push({contactId:value.id,contactVersion:1,initialPreparationAllowed:true,blockers:[],reminderCount:0})
  }else throw Error('Unexpected service operation '+value.operation)
  await route.fulfill({json:{saved:true}})
 })
 await page.goto('/sales?project=service')
 await expect(page.getByRole('heading',{name:'Säljförberedelse'})).toBeVisible()
 await expect(page.getByText('WebBuilder / Atlas',{exact:true})).toBeVisible()
 await page.getByRole('heading',{name:'Erbjudande och Atlas-uppdrag',exact:true}).click()
 await page.getByText('Spara nytt erbjudande',{exact:true}).click()
 const offerForm=page.locator('form').filter({has:page.locator('input[name="senderEmail"]')})
 await expect(offerForm.locator('[name="senderEmail"]')).toHaveValue('')
 await expect(offerForm.locator('[name="productFacts"]')).toHaveValue('')
 await offerForm.locator('[name="offerKind"]').selectOption('general_service')
 await expect(offerForm.locator('[name="freeMonths"]')).toHaveCount(0)
 await offerForm.locator('[name="offerText"]').fill('Separat projektförslag efter bekräftat underlag.')
 await offerForm.locator('[name="confirmed"]').check()
 await offerForm.getByRole('button',{name:'Spara erbjudandeversion'}).click()
 expect(await offerForm.evaluate(form=>(form as HTMLFormElement).checkValidity())).toBe(false)
 expect(writes).toHaveLength(0)
 await offerForm.locator('[name="senderEmail"]').fill('studio@example.invalid')
 await offerForm.getByRole('button',{name:'Spara erbjudandeversion'}).click()
 expect(await offerForm.evaluate(form=>(form as HTMLFormElement).checkValidity())).toBe(false)
 expect(writes).toHaveLength(0)
 await offerForm.locator('[name="productFacts"]').fill('Synthetic owner-confirmed service fact. Prissättning behöver bekräftas separat.')
 await offerForm.getByRole('button',{name:'Spara erbjudandeversion'}).click()
 await expect(page.getByRole('status')).toHaveText('Erbjudandet är sparat som en ny version.')
 expect(writes[0]).toMatchObject({operation:'save_offer',projectId,offerKind:'general_service',freeMonths:null,senderEmail:'studio@example.invalid',confirmed:true,productFacts:['Synthetic owner-confirmed service fact. Prissättning behöver bekräftas separat.']})
 await page.getByRole('heading',{name:'Kontakter',exact:true}).click()
 await page.getByText('Lägg till kontakt',{exact:true}).click()
 const contactForm=page.locator('form').filter({has:page.locator('input[name="companyName"]')})
 await contactForm.locator('[name="companyName"]').fill('Synthetic Studio Lead')
 await contactForm.locator('[name="email"]').fill('lead@example.invalid')
 await contactForm.locator('[name="offerKind"]').selectOption('general_service')
 await expect(contactForm.locator('[name="pilotMonths"]')).toHaveCount(0)
 await contactForm.locator('[name="history"]').selectOption('not_contacted')
 await contactForm.locator('[name="historySource"]').fill('Synthetic owner-confirmed contact history and service eligibility.')
 await contactForm.locator('[name="confirmed"]').check()
 await contactForm.getByRole('button',{name:'Spara kontakt',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Kontakten är sparad.')
 expect(writes[1]).toMatchObject({operation:'save_contact',projectId,offerKind:'general_service',pilotMonths:null,confirmed:true,history:'not_contacted'})
 const row=page.locator('li').filter({hasText:'Synthetic Studio Lead'})
 await expect(row).toContainText('Tjänsteerbjudande')
 await row.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Kopiera uppdrag till Atlas'}).click()
 const copied=await page.evaluate(()=>navigator.clipboard.readText())
 expect(copied).toContain('WebBuilder');expect(copied).toContain('Separat projektförslag efter bekräftat underlag.');expect(copied).toContain('Skicka inget.')
 expect(copied).not.toMatch(/Handlarbörsen|\d+ månader gratis/i)
 expect(writes.map(value=>value.operation)).toEqual(['save_offer','save_contact'])
})
