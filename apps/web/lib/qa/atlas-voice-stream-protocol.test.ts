import { describe, expect, it, vi } from 'vitest'
const protocol = () => import('@/lib/atlas/voice-pilot/stream-protocol')
describe('bounded PCM wire frames', () => {
  it('round-trips every byte of a 200 ms PCM block', async () => {
    const p = await protocol().catch(() => null)
    const pcm = Uint8Array.from({ length: 6400 }, (_, i) => i % 256)
    const frame = p?.encodeVoicePcm?.(27, pcm)
    expect(frame, 'bounded PCM encoder is missing').toBeInstanceOf(Uint8Array)
    expect(frame?.byteLength).toBe(6404)
    expect(p!.decodeVoicePcm(frame!)).toEqual({ seq: 27, pcm })
  })
  it.each([0, 1, 3, 6401, 6402])('rejects invalid PCM length %i', async size => {
    const p = await protocol()
    expect(() => p.encodeVoicePcm(0, new Uint8Array(size))).toThrow()
  })
  it.each([-1, 0.5, NaN, Infinity, 4294967296])('rejects invalid sequence %s', async seq => {
    const p = await protocol()
    expect(() => p.encodeVoicePcm(seq, new Uint8Array(2))).toThrow()
  })
  it('rejects malformed inbound frames too', async () => {
    const p = await protocol()
    for (const length of [0, 4, 5, 6405, 6406]) expect(() => p.decodeVoicePcm(new Uint8Array(length))).toThrow()
  })
})
describe('strict controls and turn sequence', () => {
  it('accepts exactly one ordered stream and matching finish boundary', async () => {
    const p = await protocol(), wire = p.createVoiceFrameState()
    expect(wire.acceptPcm(p.encodeVoicePcm(0, new Uint8Array(4)))).toEqual(new Uint8Array(4))
    wire.acceptPcm(p.encodeVoicePcm(1, new Uint8Array(6)))
    expect(wire.finish({ type: 'finish', lastSeq: 1, reason: 'pause' })).toEqual({ reason: 'pause', bytes: 10 })
    expect(() => wire.finish({ type: 'finish', lastSeq: 1, reason: 'pause' })).toThrow()
    expect(() => wire.acceptPcm(p.encodeVoicePcm(2, new Uint8Array(2)))).toThrow()
  })
  it.each(['first_gap', 'duplicate', 'out_of_order', 'finish_gap'])('rejects %s', async mode => {
    const p = await protocol(), wire = p.createVoiceFrameState()
    if (mode === 'first_gap') { expect(() => wire.acceptPcm(p.encodeVoicePcm(1, new Uint8Array(2)))).toThrow(); return }
    wire.acceptPcm(p.encodeVoicePcm(0, new Uint8Array(2)))
    if (mode === 'finish_gap') expect(() => wire.finish({ type: 'finish', lastSeq: 1, reason: 'manual' })).toThrow()
    else expect(() => wire.acceptPcm(p.encodeVoicePcm(mode === 'duplicate' ? 0 : 2, new Uint8Array(2)))).toThrow()
  })
  it('bounds total actual PCM before accepting a violating frame', async () => {
    const p = await protocol(), wire = p.createVoiceFrameState()
    for (let i = 0; i < 450; i++) wire.acceptPcm(p.encodeVoicePcm(i, new Uint8Array(6400)))
    expect(() => wire.acceptPcm(p.encodeVoicePcm(450, new Uint8Array(2)))).toThrow()
    expect(wire.finish({ type: 'finish', lastSeq: 449, reason: 'limit' })).toEqual({ bytes: 2880000, reason: 'limit' })
  })
  it('validates all control keys, UTF-8 length and allowed finish reasons', async () => {
    const p = await protocol()
    expect(p.parseVoiceControl('{"type":"cancel"}')).toEqual({ type: 'cancel' })
    expect(p.parseVoiceControl('{"type":"finish","lastSeq":0,"reason":"manual"}')).toEqual({ type: 'finish', lastSeq: 0, reason: 'manual' })
    for (const value of [null, [], { type: 'cancel', model: 'other' }, { type: 'finish', lastSeq: -1, reason: 'pause' }, { type: 'finish', lastSeq: 0, reason: 'arbitrary' }, { type: 'finish', lastSeq: 0, reason: 'pause', keyterms: ['private'] }])
      expect(() => p.parseVoiceControl(JSON.stringify(value))).toThrow()
    expect(() => p.parseVoiceControl('{"type":"cancel"}' + ' '.repeat(500))).toThrow()
    expect(() => p.parseVoiceControl('{"type":"cancel"}' + 'å'.repeat(250))).toThrow()
  })
  it('accepts only bounded safe server events and never partial transcripts', async () => {
    const p = await protocol()
    expect(p.parseVoiceServerEvent('{"type":"ready"}')).toEqual({ type: 'ready' })
    expect(p.parseVoiceServerEvent('{"type":"final","text":"Hej","reason":"pause"}')).toMatchObject({ text: 'Hej' })
    expect(p.parseVoiceServerEvent('{"type":"failed","code":"timeout"}')).toMatchObject({ code: 'timeout' })
    for (const value of [{ type: 'partial', text: 'wrong' }, { type: 'failed', code: 'private-provider-error' }, { type: 'ready', token: 'secret' }, { type: 'final', text: 'a'.repeat(12001), reason: 'pause' }])
      expect(() => p.parseVoiceServerEvent(JSON.stringify(value))).toThrow()
    expect(() => p.parseVoiceServerEvent(' '.repeat(65537))).toThrow()
  })
})
describe('committed segments belong to one user question', () => {
  it('preserves repeated speech and exact total transcript bound without logging', async () => {
    const p = await protocol(), log = vi.spyOn(console, 'info')
    const segments = p.createTranscriptSegments()
    segments.append(' Hej '); segments.append('Hej')
    expect(segments.text()).toBe('Hej Hej')
    const capped = p.createTranscriptSegments(); capped.append('a'.repeat(12000))
    expect(capped.text()).toHaveLength(12000)
    expect(() => capped.append('b')).toThrow()
    expect(log).not.toHaveBeenCalled(); log.mockRestore()
  })
  it('checkpoints at 20 seconds but never completes before the user endpoint', async () => {
    const p = await protocol(), s = p.createVoiceSegmentState()
    for (let i = 0; i < 100; i++) s.accepted(6400)
    expect(s.shouldCommit()).toBe(true); expect(s.result()).toBeNull()
    s.commitSent()
    expect(s.shouldCommit()).toBe(false)
    expect(() => s.commitSent()).toThrow()
    expect(() => s.accepted(2)).toThrow()
    s.committed('Första delen.')
    expect(s.result()).toBeNull()
    for (let i = 0; i < 100; i++) s.accepted(6400)
    s.commitSent(); s.committed('Andra delen.')
    s.accepted(6400); s.finishRequested()
    expect(s.result()).toBeNull(); expect(s.shouldCommit()).toBe(true)
    s.commitSent(); s.committed('Sista delen.')
    expect(s.result()).toBe('Första delen. Andra delen. Sista delen.')
  })
  it('finishes an empty tail using its acknowledged checkpoint', async () => {
    const p = await protocol(), s = p.createVoiceSegmentState()
    for (let i = 0; i < 100; i++) s.accepted(6400)
    s.commitSent(); s.finishRequested(); expect(s.result()).toBeNull()
    s.committed('En lång fråga.')
    expect(s.shouldCommit()).toBe(false); expect(s.result()).toBe('En lång fråga.')
    expect(() => s.accepted(2)).toThrow()
  })
  it('handles a short question and empty stable text without fabricating speech', async () => {
    const p = await protocol(), s = p.createVoiceSegmentState()
    for (let i = 0; i < 7; i++) s.accepted(6400)
    s.finishRequested(); s.commitSent(); s.committed('')
    expect(s.result()).toBe('')
    expect(() => s.committed('late duplicate')).toThrow()
  })
  it('rejects unsolicited segments, early commit and audio beyond checkpoint/total caps', async () => {
    const p = await protocol(), s = p.createVoiceSegmentState()
    expect(() => s.committed('not requested')).toThrow()
    expect(() => s.commitSent()).toThrow()
    expect(() => s.accepted(0)).toThrow(); expect(() => s.accepted(1)).toThrow()
    for (let segment = 0; segment < 4; segment++) {
      for (let i = 0; i < 100; i++) s.accepted(6400)
      expect(() => s.accepted(2)).toThrow()
      s.commitSent(); s.committed('del')
    }
    for (let i = 0; i < 50; i++) s.accepted(6400)
    expect(() => s.accepted(2)).toThrow()
    s.finishRequested(); s.commitSent(); s.committed('slut')
    expect(s.result()).toBe('del del del del slut')
  })
})
